export function codigoDe(nombre: string) {
  return nombre
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export const LOCALIDADES: Sede[] = NOMBRES.map((name) => ({ code: codigoDe(name), name })).sort((a, b) =>
  a.name.localeCompare(b.name, 'es'),
);
